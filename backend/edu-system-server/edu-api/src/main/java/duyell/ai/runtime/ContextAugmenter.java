package duyell.ai.runtime;

/**
 * **上下文增强**扩展点：在把用户问题交给模型之前，由服务端**主动**补一段上下文。
 *
 * <p><b>为什么需要这个扩展点</b>（M3 收尾的关键修复）：制度类问题靠"提示词要求模型先调检索工具"
 * 不可靠——实测 7B 会不调工具就作答，甚至复述工具的空结果文案假装查过，然后**编造文件名**
 * （例如"《教学管理办法》3.13"这种不存在的依据）。而同一句话直接打检索接口，top1 命中的就是正确条款。
 * 结论：**检索这件事不能交给模型决定**，得由服务端在意图层面判定并强制注入条款。
 *
 * <p>把扩展点定义在 {@code runtime} 包（而不是让运行时反向依赖 RAG 包）是为了保持分层：
 * 运行时只关心"有没有人要在系统提示词后面补一段"，具体补什么由实现方决定
 * （当前实现是 {@code duyell.ai.rag.PolicyContextAugmenter}）。
 * 这样也天然可测：给运行时塞一个返回固定文本的桩即可断言"注入真的发生了"。
 *
 * @author duyell
 */
public interface ContextAugmenter {

    /**
     * 针对本轮用户问题，返回要追加到系统提示词后的上下文，以及可供界面展示的出处。
     *
     * @return 注入文本 + 出处；**不需要注入时返回 {@link AugmentedContext#NONE}**
     * （早期版本返回 {@code String}，M3 收尾改成 record：注入的条款也要能显示来源卡片，
     * 否则"服务端强制检索"这条链路对用户是隐形的）
     * @implNote 实现方**不得抛异常**：增强失败绝不能拖垮一次对话（顶多让这次回答少一份依据，
     * 而抛出去会让整个请求变成错误页）。实现方自己吞掉异常并记日志。
     */
    AugmentedContext augmentFor(String userMessage);
}
